if __name__ == "__main__":
    cache = LRUCache(2)
    assert cache.get(2) == -1
    cache.put(2, 6)
    assert cache.get(1) == -1
    cache.put(1, 5)
    cache.put(1, 2)
    assert cache.get(1) == 2
    assert cache.get(2) == 6
    cache.put(3, 3)
    assert cache.get(1) == -1

    cache = LRUCache(2)
    cache.put(1, 1)
